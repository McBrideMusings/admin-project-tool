// Package compiledinfo carries the resolved manifest a compiled ./admin
// artifact (ADR-0006, admin-tlhw.6) was built from, plus which admin.toml it
// came from and when.
//
// cmd/compile.go's runCompile writes internal/compiledinfo/generated.go
// (this package's own directory, inside a temporary copy of the repo) before
// invoking `go build`, overwriting the three zero-value vars below with
// literals baked into that one build via a generated init(). A normal
// install (install.sh's build_binary) never touches this package, so every
// ordinary admin binary has ManifestB64 == "", Embedded() == false, and
// cmd.resolveProjectManifest falls back to resolving admin.toml off disk
// exactly as it does today.
package compiledinfo

import (
	"bytes"
	"encoding/base64"
	"encoding/gob"
	"fmt"

	"github.com/McBrideMusings/admin-project-tool/internal/manifest"
)

// ManifestB64 is the gob-encoded, base64-wrapped *manifest.Manifest a
// compiled artifact runs. SourcePath is the admin.toml it was resolved from
// (absolute, on the machine that ran admin compile) and BuiltAt is that
// compile's UTC timestamp (RFC 3339) — the two facts ADR-0006's frozen-
// manifest hazard requires staying visible in the artifact itself, read back
// by cmd's --compiled-info flag. All three are set only by generated.go.
var (
	ManifestB64 string
	SourcePath  string
	BuiltAt     string
)

// Concrete types encoding/gob needs registered because manifest.Manifest
// stores them behind `any`/interface fields (Raw, Actions' Action values,
// Settings, Keys, Identity, Worktrees, Beads, Workflow, Terminal, Populate)
// — the shapes github.com/BurntSushi/toml.Decode produces when it decodes a
// TOML table into map[string]any: inline tables as map[string]any, arrays as
// []any, and Action itself (a named map[string]any) for the [actions.X]
// entries. Base types (string, bool, int64, float64) are registered by gob
// automatically and need no entry here.
func init() {
	gob.Register(map[string]any{})
	gob.Register([]any{})
	gob.Register(manifest.Action{})
}

// Embedded reports whether this binary carries a frozen manifest.
func Embedded() bool { return ManifestB64 != "" }

// Load decodes the embedded manifest. Callers should check Embedded first —
// Load on a binary with none returns an error naming that rather than a
// decode failure.
func Load() (*manifest.Manifest, error) {
	if !Embedded() {
		return nil, fmt.Errorf("this admin binary has no embedded manifest — it was not produced by admin compile")
	}
	raw, err := base64.StdEncoding.DecodeString(ManifestB64)
	if err != nil {
		return nil, fmt.Errorf("decoding the embedded manifest: %w", err)
	}
	var m manifest.Manifest
	if err := gob.NewDecoder(bytes.NewReader(raw)).Decode(&m); err != nil {
		return nil, fmt.Errorf("decoding the embedded manifest: %w", err)
	}
	return &m, nil
}

// Encode gob+base64 encodes m for embedding — Load's inverse, called by
// cmd/compile.go at compile time (on the machine running admin compile,
// never inside a compiled artifact itself).
func Encode(m *manifest.Manifest) (string, error) {
	var buf bytes.Buffer
	if err := gob.NewEncoder(&buf).Encode(m); err != nil {
		return "", fmt.Errorf("encoding the resolved manifest: %w", err)
	}
	return base64.StdEncoding.EncodeToString(buf.Bytes()), nil
}

// GeneratedSource renders the generated.go file admin compile writes into
// this package's directory inside its temporary build copy. Plain Go source
// setting the three vars via init(), not -ldflags -X, because a resolved
// manifest can run past the practical size a linker -X value stays
// comfortable at and a generated file has no such limit.
func GeneratedSource(manifestB64, sourcePath, builtAtRFC3339 string) string {
	return fmt.Sprintf(`// Code generated by admin compile. DO NOT EDIT.

package compiledinfo

func init() {
	ManifestB64 = %q
	SourcePath = %q
	BuiltAt = %q
}
`, manifestB64, sourcePath, builtAtRFC3339)
}
